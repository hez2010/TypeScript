import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { api } from "../../tools/scripts/tsc/schema.ts";
import { root, sha256 } from "./common.mjs";

const input = await readFile(path.join(root, "tools/scripts/tsc/ast.json"));
const upper = name => name[0].toUpperCase() + name.slice(1);
const className = name => name.endsWith("Node") ? name : name + "Node";
const union = type => type.kind === "alias" ? union(type.resolved) : type.kind === "union" ? type : undefined;
const visible = node => node.members.filter(member => !member.noGo && !member.noTS && !member.isKindParam());
const scalar = member => !member.isChild() && member.declaredType.kind === "primitive";
const text = node => visible(node).filter(member => scalar(member) && member.declaredType.name === "string");
const manual = node => node.handWritten || visible(node).some(member => !member.isChild()
    && !(scalar(member) && ["bool", "string", "NodeFlags"].includes(member.declaredType.name))
    && !union(member.declaredType)?.types.every(type => type.kind === "kind"));
const dataType = node => node.handWritten || text(node).length > 1 || text(node).length && manual(node) ? 2 : text(node).length ? 1 : 0;
const lines = ["// <auto-generated />", "#nullable enable", `// ast.json SHA256 ${sha256(input)}`,
    "using TypeScript.Compiler.Ast;", "using TypeScript.Compiler.Syntax;", "using TypeScript.Compiler.Text;",
    "namespace TypeScript.Compiler.Protocol;", "", "internal static class AstWireSchema", "{"];
function method(signature, body) { lines.push(`    internal static ${signature}`, "    {", ...body.map(line => "        " + line), "    }", ""); }
const nodes = [...api.nodeTypeMap.values()].filter(node => node.def);
method("uint DataType(SyntaxNode node)", ["return node switch", "{",
    ...nodes.filter(node => dataType(node)).map(node => `    ${className(node.name)} => ${dataType(node)}u << 30,`), "    _ => 0", "};"]);
// Generated members below use ordinary switch statements to keep code independent of reflection.
const mask = ["switch (node)", "{"];
for (const node of nodes) {
    const children = visible(node).filter(member => member.isChild());
    if (!children.length || dataType(node)) continue;
    if (children.length > 8) throw Error(`Too many encoded child slots: ${node.name}`);
    const terms = children.map((member, i) => {
        const p = "n." + upper(member.name);
        const condition = member.listKind === "ModifierList" ? `${p} is { Count: > 0 }`
            : member.listKind === "raw" ? `${p}.Length != 0` : `${p} is not null`;
        return `(${condition} ? ${1 << i}u : 0)`;
    });
    mask.push(`    case ${className(node.name)} n: return ${terms.join(" | ")};`);
}
mask.push("    default: return 0;", "}"); method("uint ChildrenMask(SyntaxNode node)", mask);
const common = ["switch (node)", "{"];
for (const node of nodes) {
    if (node.name === "SyntheticExpression") { common.push('    case SyntheticExpressionNode: throw new InvalidDataException("Synthetic expressions cannot be encoded");'); continue; }
    if (manual(node)) continue;
    const members = visible(node).filter(member => !member.isChild());
    const bools = members.filter(member => scalar(member) && member.declaredType.name === "bool");
    const unions = members.filter(member => union(member.declaredType)?.types.every(type => type.kind === "kind"));
    if (!bools.length && !unions.length) continue;
    let shift = 24;
    const terms = bools.map(member => `(n.${upper(member.name)} ? 1u << ${shift++} : 0)`);
    for (const member of unions) {
        const values = union(member.declaredType).types;
        terms.push(`((n.${upper(member.name)} switch { ${values.map((type, i) => `SyntaxKind.${type.name} => ${i + (member.optional ? 1 : 0)}u`).join(", ")}, _ => 0u }) << ${shift})`);
        shift += Math.ceil(Math.log2(values.length + (member.optional ? 1 : 0)));
    }
    if (shift > 30) throw Error(`Common data exceeds six bits: ${node.name}`);
    common.push(`    case ${className(node.name)} n: return ${terms.join(" | ")};`);
}
common.push("    default: return 0;", "}"); method("uint CommonData(SyntaxNode node)", common);
const strings = ["switch (node)", "{"];
for (const node of nodes) if (text(node).length) {
    const member = text(node)[0], value = `n.${upper(member.name)}`;
    strings.push(`    case ${className(node.name)} n: return ${member.listKind === "raw" ? `Utf8String.Concat(${value})` : value};`);
}
strings.push('    default: throw new InvalidDataException("Node has no encoded text");', "}"); method("Utf8String Text(SyntaxNode node)", strings);
const visit = ["switch (node)", "{"];
for (const node of nodes) {
    let children = node.members.filter(member => !member.noGo && !member.goOnly && member.isChild());
    if (!children.length) continue;
    visit.push(`    case ${className(node.name)} n:`);
    // The binary encoder uses VisitEachChild, whose JSDoc parameter traversal
    // follows schema order; ordinary ForEachChild uses source order instead.
    for (const member of children.toReversed()) {
        const p = "n." + upper(member.name);
        const guard = member.condition ? `if (${member.condition}) ` : "";
        if (member.listKind === "raw") visit.push(`        for (int i = ${p}.Length - 1; i >= 0; i--) stack.Push(new(${p}[i], null, parent));`);
        else if (member.listKind) visit.push(`        if (${p} is {${member.listKind === "ModifierList" ? " Count: > 0 " : " "}}) stack.Push(new(null, ${p}, parent));`);
        else visit.push(`        ${guard}if (${p} is not null) stack.Push(new(${p}, null, parent));`);
    }
    visit.push("        break;");
}
visit.push("}"); method("void PushChildren(SyntaxNode node, uint parent, Stack<AstWireFrame> stack)", visit);
const create = ["return kind switch", "{"];
const syntaxKinds = new Set(JSON.parse(input).kinds.elements.map(kind => typeof kind === "string" ? kind : kind.name).filter(Boolean));
const nodeKinds = new Map(api.syntaxKindToNodeInfo);
for (const node of nodes) {
    const kinds = union(node.members.find(member => member.isKindParam())?.declaredType ?? {});
    for (const kind of kinds?.types ?? []) if (kind.kind === "kind") nodeKinds.set(kind.name, { nodeName: node.name });
}
for (const name of ["Token", "KeywordExpression", "KeywordTypeNode"]) {
    const kind = api.nodeTypeMap.get(name).members.find(member => member.name === "Kind").declaredType;
    for (const type of union(kind.constraint).types)
        if (name !== "Token" || !nodeKinds.has(type.name)) nodeKinds.set(type.name, { nodeName: name });
}
for (const [kind, info] of nodeKinds) {
    if (!syntaxKinds.has(kind) || info.nodeName === "SyntheticExpression") continue;
    const definition = api.nodeTypeMap.get(info.nodeName).def;
    const kindMember = definition.members?.find(member => member.name === "Kind");
    const parameterized = Array.isArray(definition.kind) || Array.isArray(kindMember?.type) || ["Token", "KeywordExpression", "KeywordTypeNode"].includes(info.nodeName);
    create.push(`    SyntaxKind.${kind} => new ${className(info.nodeName)}(${parameterized ? "kind" : ""}),`);
}
create.push('    _ => throw new InvalidDataException($"Unsupported AST kind: {kind}")', "};");
method("SyntaxNode Create(SyntaxKind kind)", create);
const readCommon = ["switch (node)", "{"];
for (const node of nodes) {
    if (manual(node)) continue;
    const members = visible(node).filter(member => !member.isChild());
    const bools = members.filter(member => scalar(member) && member.declaredType.name === "bool");
    const unions = members.filter(member => union(member.declaredType)?.types.every(type => type.kind === "kind"));
    if (!bools.length && !unions.length) continue;
    readCommon.push(`    case ${className(node.name)} n:`);
    let shift = 24;
    for (const member of bools) readCommon.push(`        n.${upper(member.name)} = (data & (1u << ${shift++})) != 0;`);
    for (const member of unions) {
        const values = union(member.declaredType).types;
        const bits = Math.ceil(Math.log2(values.length + (member.optional ? 1 : 0)));
        const cases = values.map((type, i) => `${i + (member.optional ? 1 : 0)} => SyntaxKind.${type.name}`);
        if (member.optional) cases.unshift("0 => SyntaxKind.Unknown");
        readCommon.push(`        n.${upper(member.name)} = ((data >> ${shift}) & ${(1 << bits) - 1}) switch { ${cases.join(", ")}, _ => throw new InvalidDataException("Invalid AST common data") };`);
        shift += bits;
    }
    readCommon.push("        break;");
}
readCommon.push("}"); method("void ReadCommon(SyntaxNode node, uint data)", readCommon);
const setText = ["switch (node)", "{"];
for (const node of nodes) if (text(node).length) {
    const member = text(node)[0];
    setText.push(`    case ${className(node.name)} n: n.${upper(member.name)} = ${member.listKind === "raw" ? "[value]" : "value"}; break;`);
}
setText.push('    default: throw new InvalidDataException("Node has no encoded text");', "}");
method("void SetText(SyntaxNode node, Utf8String value)", setText);
const readChildren = ["switch (node)", "{"];
for (const node of nodes) {
    const children = node.members.filter(member => !member.noGo && !member.goOnly && member.isChild());
    if (!children.length) continue;
    readChildren.push(`    case ${className(node.name)} n:`);
    let bit = 0;
    for (let i = 0; i < children.length; i++) {
        const member = children[i];
        const type = api.nodeTypeMap.get(member.declaredType.name)?.def ? className(member.declaredType.name) : "SyntaxNode";
        let value;
        if (member.noTS) {
            if (member.name !== "FullSignature") throw Error(`Unhandled internal child: ${node.name}.${member.name}`);
            const rest = children.slice(i + 1).filter(member => !member.noTS).length;
            value = `children.ExtraNode(mask, ${bit}, ${rest})`;
        } else if (node.name === "SourceFile") value = member.listKind ? "children.List()" : "children.Node<SyntaxNode>()";
        else if (dataType(node) === 1) {
            if (children.length !== 1 || member.listKind) throw Error(`Unsupported string node children: ${node.name}`);
            value = `children.OptionalNode<${type}>()`;
        }
        else {
            value = member.listKind === "raw" ? `children.Raw(mask, ${bit})` : member.listKind ? `children.List(mask, ${bit})` : `children.Node<${type}>(mask, ${bit})`;
            bit++;
        }
        readChildren.push(`        n.${upper(member.name)} = ${value};`);
    }
    readChildren.push("        break;");
}
readChildren.push("}"); method("void ReadChildren(SyntaxNode node, uint mask, ref AstChildReader children)", readChildren);
lines.push("}", "");
const file = path.join(root, "csharp/src/TypeScript.Compiler/Protocol/AstWireSchema.generated.cs");
const output = lines.join("\n");
if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")).replaceAll("\r\n", "\n") !== output) throw Error("Stale AST wire schema");
} else await writeFile(file, output);
