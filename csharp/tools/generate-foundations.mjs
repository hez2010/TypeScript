// Data generation only: semantic algorithms are implemented in C#.
import {
    mkdir,
    readFile,
    writeFile,
} from "node:fs/promises";
import path from "node:path";
import {
    root,
    sha256,
} from "./common.mjs";

async function emit(relative, lines) {
    const file = path.join(root, "csharp/src/TypeScript.Compiler", relative);
    const text = lines.join("\n") + "\n";
    if (process.argv.includes("--check")) {
        if ((await readFile(file, "utf8")).replaceAll("\r\n", "\n") !== text) throw new Error(`Stale ${relative}`);
    }
    else {
        await mkdir(path.dirname(file), { recursive: true });
        await writeFile(file, text);
    }
}
for (const name of ["TokenFlags", "NodeFlags"]) {
    const bytes = await readFile(path.join(root, `tsc/internal/ast/${name.toLowerCase()}.go`));
    const lines = ["// <auto-generated />", `// Source SHA256 ${sha256(bytes)}`, "namespace TypeScript.Compiler.Syntax;", "[Flags]", `public enum ${name} : uint`, "{"];
    for (const match of bytes.toString().matchAll(new RegExp(`^\\s*${name}(\\w+)\\s+(?:${name}\\s+)?=([^\\n]+)`, "gm"))) {
        lines.push(`    ${match[1]} = ${match[2].split("//")[0].trim().replaceAll(name, "")},`);
    }
    lines.push("}");
    await emit(`Syntax/${name}.generated.cs`, lines);
}
const goDiagnostics = await readFile(path.join(root, "tsc/internal/diagnostics/diagnostics_generated.go"), "utf8");
const diagnostics = [...goDiagnostics.matchAll(/var (\w+) = &Message\{code: (\d+), category: Category(\w+), key: ("(?:\\.|[^"\\])*"), text: ("(?:\\.|[^"\\])*")(.*?)\}/g)];
if (diagnostics.length < 2000) throw new Error("Incomplete diagnostic input");
const messages = ["// <auto-generated />", `// Source SHA256 ${sha256(goDiagnostics)}`, "namespace TypeScript.Compiler.Diagnostics;", "public static class Messages", "{"];
const codeName = name => name.split("_").map(part => part.charAt(0).toUpperCase() + part.slice(1)).join("");
const codeNames = diagnostics.map(d => codeName(d[1]));
if (new Set(codeNames).size !== diagnostics.length) throw Error("Duplicate diagnostic enum member");
await emit("Diagnostics/DiagnosticCode.generated.cs", [
    "// <auto-generated />",
    `// Source SHA256 ${sha256(goDiagnostics)}`,
    "namespace TypeScript.Compiler.Diagnostics;",
    "",
    "public enum DiagnosticCode",
    "{",
    "    Custom = -1,",
    "    None = 0,",
    ...diagnostics.map(([, name, code]) => `    ${codeName(name)} = ${code},`),
    "}",
]);
for (const [, name, , category, key, text, rest] of diagnostics) messages.push(`    public static readonly DiagnosticMessage ${name} = new(DiagnosticCode.${codeName(name)}, DiagnosticCategory.${category}, ${key}u8, ${text}u8, ${rest.includes("reportsUnnecessary: true")}, ${rest.includes("reportsDeprecated: true")}, ${rest.includes("elidedInCompatibilityPyramid: true")});`);
messages.push("    public static IReadOnlyList<DiagnosticMessage> All { get; } = Array.AsReadOnly<DiagnosticMessage>([", ...diagnostics.map(d => `        ${d[1]},`), "    ]);", "}");
await emit("Diagnostics/Messages.generated.cs", messages);
const scanner = await readFile(path.join(root, "tsc/internal/scanner/scanner.go"), "utf8");
const tokens = [...scanner.slice(0, scanner.indexOf("type ScannerState")).matchAll(/\s*("(?:\\.|[^"\\])*"):\s*ast.Kind(\w+),/g)];
const tokenFacts = ["// <auto-generated />", "using TypeScript.Compiler.Text;", "namespace TypeScript.Compiler.Syntax;", "public static partial class TokenFacts", "{",
    "    public static SyntaxKind FromText(ReadOnlySpan<byte> text) => text.Length switch", "    {"];
const byLength = Map.groupBy(tokens, ([, text]) => JSON.parse(text).length);
for (const [length, group] of [...byLength].sort((a, b) => a[0] - b[0])) {
    tokenFacts.push(`        ${length} => text[0] switch`, "        {");
    for (const [first, entries] of Map.groupBy(group, ([, text]) => JSON.parse(text)[0])) {
        const matches = entries.map(([, text, kind]) => `text.SequenceEqual(${text}u8) ? SyntaxKind.${kind} : `).join("");
        tokenFacts.push(`            (byte)'${first}' => ${length === 1 ? `SyntaxKind.${entries[0][2]}` : matches + "SyntaxKind.Unknown"},`);
    }
    tokenFacts.push("            _ => SyntaxKind.Unknown,", "        },");
}
tokenFacts.push("        _ => SyntaxKind.Unknown,", "    };",
    "    internal static SyntaxKind Punctuation(ReadOnlySpan<byte> text, out int length)", "    {",
    "        if (text.IsEmpty) { length = 0; return SyntaxKind.Unknown; }", "        switch (text[0])", "        {");
const punctuation = tokens.filter(([, , kind]) => !kind.endsWith("Keyword") && !["HashToken", "BacktickToken"].includes(kind));
for (const [first, entries] of Map.groupBy(punctuation, ([, text]) => JSON.parse(text)[0])) {
    tokenFacts.push(`            case (byte)'${first}':`);
    for (const [, text, kind] of entries.toSorted((a, b) => JSON.parse(b[1]).length - JSON.parse(a[1]).length)) {
        const length = JSON.parse(text).length;
        tokenFacts.push(...length === 1 ? [`                length = 1; return SyntaxKind.${kind};`]
            : [`                if (text.StartsWith(${text}u8)) { length = ${length}; return SyntaxKind.${kind}; }`]);
    }
}
tokenFacts.push("        }", "        length = 0;", "        return SyntaxKind.Unknown;", "    }",
    ...tokens.map(([, text, kind]) => `    private static readonly Utf8String Text${kind} = Utf8String.Copy(${text}u8);`),
    "    public static Utf8String Text(SyntaxKind kind) => kind switch", "    {", ...tokens.map(([, , kind]) => `        SyntaxKind.${kind} => Text${kind},`), '        _ => default,', "    };", "}");
await emit("Syntax/TokenFacts.generated.cs", tokenFacts);
console.log(`Generated flags, ${diagnostics.length} diagnostics, and ${tokens.length} tokens`);
const unicode = await readFile(path.join(root, "tsc/internal/stringutil/identifier_parts_generated.go"), "utf8");
const unicodeLines = ["// <auto-generated />", "// Unicode 15.1 ID_Start/ID_Continue: pinned language data, independent of OS Unicode version.", "namespace TypeScript.Compiler.Syntax;", "public static partial class TokenFacts", "{"];
for (const name of ["Start", "Part"]) {
    const section = unicode.split(`var unicodeESNextIdentifier${name} = `)[1].split("var ")[0];
    const values = new Set();
    for (const [, lower, upper, step] of section.matchAll(/\{(0x[0-9a-fA-F]+), (0x[0-9a-fA-F]+), (\d+)\}/g)) for (let i = Number(lower); i <= Number(upper); i += Number(step)) values.add(i);
    const ranges = [];
    for (const value of [...values].sort((a, b) => a - b)) {
        if (ranges.length && value === ranges.at(-1) + 1) ranges[ranges.length - 1] = value;
        else ranges.push(value, value);
    }
    // Half-open intervals let the BCL binary search handle both boundaries uniformly.
    const boundaries = ranges.map((v, i) => i % 2 ? v + 1 : v);
    unicodeLines.push(`    private static ReadOnlySpan<int> Identifier${name}Boundaries => [`, ...Array.from({ length: Math.ceil(boundaries.length / 16) }, (_, i) => `        ${boundaries.slice(i * 16, (i + 1) * 16).join(", ")},`), "    ];");
}
unicodeLines.push("}");
await emit("Syntax/IdentifierRanges.generated.cs", unicodeLines);
