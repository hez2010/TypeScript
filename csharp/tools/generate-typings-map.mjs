import { readFile, writeFile, mkdir } from "node:fs/promises";
import assert from "node:assert/strict";
import path from "node:path";
import { root, sha256 } from "./common.mjs";
const source = await readFile(path.join(root, "tsc/internal/project/ata/typesmap.go"), "utf8");
const table = source.slice(source.indexOf("var safeFileNameToTypeName = map[string]string{"));
const entries = [...table.matchAll(/^\s*("(?:[^"\\]|\\.)*"):\s*("(?:[^"\\]|\\.)*"),/gm)].map(match => [JSON.parse(match[1]), JSON.parse(match[2])]);
if (entries.length < 100) throw Error("Missing reference typings map");
const directory = path.join(root, "csharp/src/TypeScript.Compiler/Projects/TypeAcquisition");
await mkdir(directory, { recursive: true });
const code = `// <auto-generated />\n// project/ata/typesmap.go SHA256 ${sha256(source)}\nusing System.Collections.Frozen;\n\nnamespace TypeScript.Compiler.Projects.TypeAcquisition;\n\ninternal static class TypingsMap\n{\n    internal static readonly FrozenDictionary<Utf8String, Utf8String> FileNames = new Dictionary<Utf8String, Utf8String>\n    {\n${entries.map(([key,value]) => `        [${JSON.stringify(key)}u8] = ${JSON.stringify(value)}u8,`).join("\n")}\n    }.ToFrozenDictionary(Utf8StringComparer.Ordinal);\n}\n`;
const target = path.join(directory, "TypingsMap.generated.cs");
if (process.argv.includes("--check")) assert.equal((await readFile(target, "utf8")).replaceAll("\r\n", "\n"), code);
else await writeFile(target, code);
console.log(`${process.argv.includes("--check") ? "Checked" : "Generated"} ${entries.length} filename-to-typings mappings`);
