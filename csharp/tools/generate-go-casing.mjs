import {
    mkdir,
    readFile,
    writeFile,
} from "node:fs/promises";
import path from "node:path";
import {
    output,
    root,
    run,
    sha256,
} from "./common.mjs";

const option = (key, fallback) => process.argv.includes(key) ? process.argv[process.argv.indexOf(key) + 1] : fallback;
const go = option("--go", "D:/go1.27.1-20260904.9.windows-amd64/go/bin/go.exe");
const directory = path.join(output, "go-casing-generator");
await mkdir(directory, { recursive: true });
const program = `package main
import("encoding/json";"os";"unicode")
func main(){
 lower,fold:=[][2]int{},[][2]int{}
 for r:=rune(0);r<=unicode.MaxRune;r++ {
  if x:=unicode.ToLower(r);x!=r {lower=append(lower,[2]int{int(r),int(x)})}
  if x:=unicode.SimpleFold(r);x!=r {fold=append(fold,[2]int{int(r),int(x)})}
 }
 if err:=json.NewEncoder(os.Stdout).Encode(map[string]any{"version":unicode.Version,"lower":lower,"fold":fold});err!=nil {panic(err)}
}
`;
const source = path.join(directory, "main.go");
await writeFile(source, program);
const data = JSON.parse(await run(go, ["run", source], { env: { ...process.env, GOWORK: "off", GOTOOLCHAIN: "local" } }));
const lines = ["// <auto-generated />", `// Go Unicode ${data.version}; table SHA256 ${sha256(JSON.stringify(data))}`, "namespace TypeScript.Compiler.Semantics;", "internal static partial class GoUnicode", "{"];
for (const name of ["lower", "fold"]) {
    lines.push(`    private static ReadOnlySpan<int> ${name === "lower" ? "LowerMap" : "FoldMap"} =>`, "    [");
    for (const [from, to] of data[name]) lines.push(`        0x${from.toString(16)}, 0x${to.toString(16)},`);
    lines.push("    ];");
}
lines.push("}", "");
const target = path.join(root, "csharp/src/TypeScript.Compiler/Semantics/GoUnicode.generated.cs"), text = lines.join("\n");
if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")).replaceAll("\r\n", "\n") !== text) throw Error(`Stale ${target}`);
}
else await writeFile(target, text);
