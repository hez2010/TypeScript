import {
    mkdir,
    readFile,
    writeFile,
} from "node:fs/promises";
import path from "node:path";
import {
    root,
    sha256,
} from "./common.mjs";

const snapshot = JSON.parse(await readFile(path.join(root, "csharp/data/regexp-properties.json"), "utf8"));
const data = snapshot.data;
const canonical = name => name.replace(/[_ -]/g, "").toLowerCase();
const tables = [],
    keys = new Map(),
    ids = value => {
        const key = JSON.stringify(value);
        if (!keys.has(key)) {
            keys.set(key, tables.length);
            tables.push(value);
        }
        return keys.get(key);
    };
const properties = new Map();
for (const name of Object.keys(data.tables).sort()) properties.set(canonical(name), data.tables[name].map(ids));
const lines = ["// <auto-generated />", `// Pinned Go Unicode ${data.version} regexp properties; SHA256 ${sha256(JSON.stringify(data))}`, "#nullable enable", "namespace TypeScript.Compiler.Semantics;", "internal sealed partial class GoRegex", "{", "    private static int[]? Property(string name, bool fold)", "    {", "        var key = new System.Text.StringBuilder(name.Length);", "        foreach (char c in name) if (c is not ('_' or '-' or ' ')) key.Append(c is >= 'A' and <= 'Z' ? (char)(c + 32) : c);", "        return key.ToString() switch", "        {"];
for (const [name, [normal, fold]] of [...properties].sort(([a], [b]) => a.localeCompare(b))) lines.push(`            "${name}" => ${normal === fold ? `Property${normal}` : `fold ? Property${fold} : Property${normal}`},`);
lines.push("            _ => null", "        };", "    }");
for (const [id, values] of tables.entries()) {
    lines.push(`    private static readonly int[] Property${id} =`, "    [");
    for (let i = 0; i < values.length; i += 12) lines.push("        " + values.slice(i, i + 12).map(v => `0x${v.toString(16)}`).join(", ") + ",");
    lines.push("    ];");
}
lines.push("}", "");
const target = path.join(root, "csharp/src/TypeScript.Compiler/Semantics/GoRegex.Properties.generated.cs"), text = lines.join("\n");
if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")).replaceAll("\r\n", "\n") !== text) throw Error(`Stale ${target}`);
}
else await writeFile(target, text);
console.log(JSON.stringify({ version: data.version, properties: properties.size, tables: tables.length, tableSha256: sha256(JSON.stringify(data)) }));
