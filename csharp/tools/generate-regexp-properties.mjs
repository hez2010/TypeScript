import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { output, root, run, sha256 } from "./common.mjs";

const option = (key, fallback) => process.argv.includes(key) ? process.argv[process.argv.indexOf(key) + 1] : fallback;
const go = option("--go", "D:/go1.27.1-20260904.9.windows-amd64/go/bin/go.exe");
const directory = path.join(output, "regexp-property-generator");
await mkdir(directory, { recursive: true });
const source = path.join(directory, "main.go");
await writeFile(source, `package main
import("encoding/json";"os";"unicode";"regexp/syntax")
func main(){
 names:=map[string]bool{"Any":true,"Assigned":true,"ASCII":true}
 for name:=range unicode.Categories { names[name]=true }; for name:=range unicode.CategoryAliases { names[name]=true }; for name:=range unicode.Scripts { names[name]=true }
 tables:=map[string][][]rune{}
 for name:=range names {
  parts:=[][]rune{}
  for _,flag:=range []syntax.Flags{syntax.Perl,syntax.Perl|syntax.FoldCase} {
   expr,err:=syntax.Parse("\\\\p{"+name+"}",flag);if err!=nil {panic(err)}
   values:=expr.Rune
   if expr.Op==syntax.OpAnyChar {values=[]rune{0,unicode.MaxRune}} else if expr.Op==syntax.OpLiteral {values=[]rune{values[0],values[0]}}
   parts=append(parts,values)
  };tables[name]=parts
 }
 json.NewEncoder(os.Stdout).Encode(map[string]any{"version":unicode.Version,"tables":tables})
}
`);
const data = JSON.parse(await run(go, ["run", source], { cwd: path.join(root, "tsc"), env: { ...process.env, GOWORK: "off", GOTOOLCHAIN: "local" } }));
const canonical = name => name.replace(/[_ -]/g, "").toLowerCase();
const tables = [], keys = new Map(), ids = value => {
    const key = JSON.stringify(value);
    if (!keys.has(key)) { keys.set(key, tables.length); tables.push(value); }
    return keys.get(key);
};
const properties = new Map();
for (const name of Object.keys(data.tables).sort()) properties.set(canonical(name), data.tables[name].map(ids));
const lines = ["// <auto-generated />", `// Pinned Go Unicode ${data.version} regexp properties; SHA256 ${sha256(JSON.stringify(data))}`,
    "#nullable enable", "namespace TypeScript.Compiler.Semantics;", "internal sealed partial class GoRegex", "{",
    "    private static int[]? Property(string name, bool fold)", "    {",
    "        var key = new System.Text.StringBuilder(name.Length);",
    "        foreach (char c in name) if (c is not ('_' or '-' or ' ')) key.Append(c is >= 'A' and <= 'Z' ? (char)(c + 32) : c);",
    "        return key.ToString() switch", "        {"];
for (const [name, [normal, fold]] of [...properties].sort(([a], [b]) => a.localeCompare(b)))
    lines.push(`            "${name}" => ${normal === fold ? `Property${normal}` : `fold ? Property${fold} : Property${normal}`},`);
lines.push("            _ => null", "        };", "    }");
for (const [id, values] of tables.entries()) {
    lines.push(`    private static readonly int[] Property${id} =`, "    [");
    for (let i = 0; i < values.length; i += 12) lines.push("        " + values.slice(i, i + 12).map(v => `0x${v.toString(16)}`).join(", ") + ",");
    lines.push("    ];");
}
lines.push("}", "");
const target = path.join(root, "csharp/src/TypeScript.Compiler/Semantics/GoRegex.Properties.generated.cs"), text = lines.join("\n");
if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")).replaceAll("\r\n", "\n") !== text) throw Error(`Stale ${target}`);
} else await writeFile(target, text);
console.log(JSON.stringify({ version: data.version, properties: properties.size, tables: tables.length, tableSha256: sha256(JSON.stringify(data)) }));
