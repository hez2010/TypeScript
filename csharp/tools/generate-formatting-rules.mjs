import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { root, sha256 } from "./common.mjs";

const sourcePath = "tsc/internal/format/rules.go";
const source = await readFile(path.join(root, sourcePath), "utf8");
// Only the declarative token-pair rules are generated. Context evaluation, scanning,
// indentation, and edit production are implemented by the managed formatter.
const code = source.replace(/"(?:\\.|[^"\\])*"|\/\/[^\n]*|\/\*[\s\S]*?\*\//g, token => token.startsWith('"') ? token : " ");
const upper = value => value[0].toUpperCase() + value.slice(1);
function split(text) {
    const parts = []; let depth = 0, start = 0, quoted = false;
    for (let i = 0; i < text.length; i++) {
        const ch = text[i];
        if (ch === '"' && text[i - 1] !== "\\") quoted = !quoted;
        if (quoted) continue;
        if ("({[".includes(ch)) depth++;
        if (")}]".includes(ch)) depth--;
        if (ch === "," && depth === 0) { parts.push(text.slice(start, i).trim()); start = i + 1; }
    }
    if (text.slice(start).trim()) parts.push(text.slice(start).trim());
    return parts;
}
function matching(text, start) {
    let depth = 0, quoted = false;
    for (let i = start; i < text.length; i++) {
        const ch = text[i];
        if (ch === '"' && text[i - 1] !== "\\") quoted = !quoted;
        if (quoted) continue;
        if ("({[".includes(ch)) depth++;
        if (")}]".includes(ch) && --depth === 0) return i;
    }
    throw new Error("Unclosed rule expression");
}
function tokens(text) {
    text = text.trim().replaceAll("ast.Kind", "K.");
    const array = /^\[\]K\.\{([\s\S]*)\}$/.exec(text);
    if (array) return `Tokens(${split(array[1]).join(", ")})`;
    return text.replace(/^tokenRangeFrom\(/, "Tokens(").replace(/^tokenRangeFromRange\(/, "Range(")
        .replace(/^anyTokenExcept\(/, "Except(");
}
function predicate(text) {
    let match;
    if ((match = /^optionEquals\(semicolonOption, lsutil.SemicolonPreference(\w+)\)$/.exec(text)))
        return `P(static c => c.Options.Semicolons == SemicolonPreference.${match[1]})`;
    if ((match = /^isOption(Enabled|Disabled|DisabledOrUndefined|EnabledOrUndefined|DisabledOrUndefinedOrTokensOnSameLine)\((\w+)Option\)$/.exec(text))) {
        const comparison = { Enabled: "== true", Disabled: "== false", DisabledOrUndefined: "!= true", EnabledOrUndefined: "!= false",
            DisabledOrUndefinedOrTokensOnSameLine: "!= true || c.TokensOnOneLine" }[match[1]];
        return `P(static c => c.Options.${upper(match[2])} ${comparison})`;
    }
    assert.match(text, /^is\w+$/);
    return `P(${upper(text)})`;
}
const declarations = [];
const prefix = code.slice(0, code.indexOf("highPriorityCommonRules :="));
for (const match of prefix.matchAll(/(\w+) := \[\]ast.Kind\{/g)) {
    const start = match.index + match[0].length - 1, end = matching(prefix, start);
    declarations.push(`        var ${match[1]} = ${tokens("[]ast.Kind" + prefix.slice(start, end + 1))};`);
}
for (const match of prefix.matchAll(/(\w+) := (tokenRangeFrom(?:Range)?\([^\n]+\))/g))
    declarations.push(`        var ${match[1]} = ${tokens(match[2])};`);
assert.equal(declarations.length, 13, "Review changed formatter token groups");
const rules = [];
for (const match of code.matchAll(/\brule\(/g)) {
    const start = match.index + match[0].length - 1, end = matching(code, start);
    const args = split(code.slice(start + 1, end));
    assert.ok(args.length === 5 || args.length === 6);
    let predicates = "[]";
    if (args[3] !== "anyContext") {
        const values = /^\[\]contextPredicate\{([\s\S]*)\}$/.exec(args[3]); assert.ok(values);
        predicates = `[${split(values[1]).map(predicate).join(", ")}]`;
    }
    if (args[5]) assert.equal(args[5], "ruleFlagsCanDeleteNewLines");
    const action = args[4].replace(/^ruleAction/, "FormattingAction.");
    rules.push(`            R(${args[0]}, ${tokens(args[1])}, ${tokens(args[2])}, ${predicates}, ${action}${args[5] ? ", true" : ""}),`);
}
assert.equal(rules.length, 135, "Review changed formatter rule count");
const result = `// <auto-generated />\n// ${sourcePath}; SHA256 ${sha256(source)}\nusing K = TypeScript.Compiler.Syntax.SyntaxKind;\n\nnamespace TypeScript.Compiler.LanguageServices;\n\ninternal static partial class FormattingRules\n{\n    private static RuleSpec[] CreateRules()\n    {\n        var allTokens = Range(K.FirstToken, K.LastToken).Tokens.Where(kind => kind != K.EndOfFile).ToArray();\n        var anyToken = new TokenSet(allTokens, false);\n        TokenSet Except(params K[] excluded) => new(allTokens.Where(kind => !excluded.Contains(kind)).ToArray(), false);\n        var anyTokenIncludingMultilineComments = Tokens([.. allTokens, K.MultiLineCommentTrivia]);\n        var anyTokenIncludingEOF = Tokens([.. allTokens, K.EndOfFile]);\n${declarations.join("\n")}\n        var typeNames = Tokens([K.Identifier, .. typeKeywords.Tokens]);\n        var functionOpenBraceLeftTokenRange = anyTokenIncludingMultilineComments;\n        return\n        [\n${rules.join("\n")}\n        ];\n    }\n}\n`;
const target = path.join(root, "csharp/src/TypeScript.Compiler/LanguageServices/Formatting/FormattingRules.generated.cs");
if (process.argv.includes("--check")) assert.equal(await readFile(target, "utf8"), result);
else await writeFile(target, result);
console.log(`${rules.length} formatting rules`);
