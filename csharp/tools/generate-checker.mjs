import {
    mkdir,
    readFile,
    writeFile,
} from "node:fs/promises";
import path from "node:path";
import {
    root,
    sha256,
} from "./common.mjs";

// Generate constant schemas only. Semantic algorithms are ported and reviewed separately.
const groups = {
    "types.go": ["TypeFlags", "ObjectFlags", "SignatureFlags", "ElementFlags", "AccessFlags", "IndexFlags", "VarianceFlags", "NodeCheckFlags", "TypePredicateKind", "SignatureKind", "Ternary", "ContextFlags"],
    "checker.go": ["TypeSystemPropertyName", "UnionReduction", "IntersectionFlags", "MappedTypeModifiers", "MappedTypeNameTypeKind", "TypeFacts", "InferenceFlags", "InferencePriority", "CheckMode", "WideningKind", "IterationUse", "IterationTypeKind", "DeclarationSpaces"],
    "relater.go": ["SignatureCheckMode", "MinArgumentCountFlags", "IntersectionState", "RecursionFlags", "ExpandingFlags", "RelationComparisonResult"],
};
const lines = ["// <auto-generated />", "namespace TypeScript.Compiler.Checking;", ""];
for (const [file, names] of Object.entries(groups)) {
    const bytes = await readFile(path.join(root, "tsc/internal/checker", file));
    lines.push(`// ${file} SHA256 ${sha256(bytes)}`);
    const source = bytes.toString().replaceAll(/\/\/[^\n]*/g, "").replaceAll(/\|\s*\n\s*/g, "| ");
    for (const name of names) {
        const block = [...source.matchAll(/const\s*\(([\s\S]*?)\n\)/g)].find(m => new RegExp(`\\b${name}\\w+\\b`).test(m[1]));
        if (!block) throw Error(`Missing ${name}`);
        const flags = name.endsWith("Flags") || ["MappedTypeModifiers", "SignatureCheckMode", "IntersectionState", "RelationComparisonResult", "TypeFacts", "InferencePriority", "CheckMode", "IterationUse", "DeclarationSpaces"].includes(name), backing = name === "Ternary" ? "sbyte" : name === "InferencePriority" ? "int" : flags ? "uint" : "int";
        if (flags) lines.push("[Flags]");
        lines.push(`public enum ${name} : ${backing}`, "{");
        let index = 0, previous;
        for (const row of block[1].split("\n").map(s => s.trim()).filter(Boolean)) {
            const match = row.match(new RegExp(`^${name}(\\w+)(?:\\s+${name})?(?:\\s*=\\s*(.*))?$`));
            if (!match) throw Error(`Unrecognized ${name} constant: ${row}`);
            const expression = match[2] ?? previous;
            if (!expression) throw Error(`Missing expression: ${row}`);
            previous = expression;
            let value = expression.replaceAll("iota", String(index++)).replaceAll(name, "").replaceAll(/&\s*\^/g, "& ~");
            if (backing === "uint") value = value.replaceAll(/\b1\s*<</g, "1u <<");
            lines.push(`    ${match[1]} = ${value},`);
        }
        lines.push("}", "");
    }
}
const file = path.join(root, "csharp/src/TypeScript.Compiler/Checking/Flags.generated.cs"), text = lines.join("\n");
if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")).replaceAll("\r\n", "\n") !== text) throw Error(`Stale ${file}`);
}
else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, text);
}

const utilities = await readFile(path.join(root, "tsc/internal/checker/utilities.go"));
const utilitySource = utilities.toString().replaceAll("\r\n", "\n");
const featureStart = utilitySource.indexOf("var getFeatureMap =");
const featureMap = utilitySource.slice(featureStart, utilitySource.indexOf("\n})", featureStart));
const features = ["// <auto-generated />", "#nullable enable", `// utilities.go SHA256 ${sha256(utilities)}`, "namespace TypeScript.Compiler.Checking;", "", "internal static class LibraryFeatures", "{", "    internal static string? PropertyLibrary(string? type, string property) => (type, property) switch", "    {"];
const typePattern = /\t\t"([^"]+)": \{([\s\S]*?)\n\t\t\},/g;
const entryPattern = /\{lib: "([^"]+)", props: \[\]string\{([\s\S]*?)\}\},/g;
let featureTypes = 0;
for (const type of featureMap.matchAll(typePattern)) {
    featureTypes++;
    if (type[2].replaceAll(entryPattern, "").trim()) throw Error(`Unrecognized feature entries for ${type[1]}`);
    for (const entry of type[2].matchAll(entryPattern)) {
        const properties = [...entry[2].matchAll(/"([^"]+)"/g)].map(p => JSON.stringify(p[1]));
        if (entry[2].replaceAll(/"[^"]+"|[\s,]/g, "")) throw Error(`Unrecognized feature properties for ${type[1]}`);
        if (properties.length) features.push(`        (${JSON.stringify(type[1])}, ${properties.join(" or ")}) => ${JSON.stringify(entry[1])},`);
    }
}
if (!featureTypes || featureMap.replaceAll(typePattern, "").replace(/^var getFeatureMap = sync.OnceValue\(func\(\) map\[string\]\[\]FeatureMapEntry \{\s*return map\[string\]\[\]FeatureMapEntry\{/, "").replaceAll(/[\s}]/g, "")) throw Error("Unrecognized library feature map");
features.push("        _ => null", "    };", "}", "");
const featureFile = path.join(root, "csharp/src/TypeScript.Compiler/Checking/LibraryFeatures.generated.cs"), featureText = features.join("\n");
if (process.argv.includes("--check")) {
    if ((await readFile(featureFile, "utf8")).replaceAll("\r\n", "\n") !== featureText) throw Error(`Stale ${featureFile}`);
}
else await writeFile(featureFile, featureText);
