import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { root, sha256 } from "./common.mjs";

const bytes = await readFile(path.join(root, "tools/scripts/tsc/ast.json"));
const schema = JSON.parse(bytes), definitions = schema.nodes.definitions;
const names = new Set(Object.keys(definitions));
const scalar = new Set(["string", "bool", "NodeFlags", "TokenFlags", "ImportPhaseModifierSyntaxKind", "TKind", "any"]);
const className = name => name.endsWith("Node") ? name : name + "Node";
const upper = name => name[0].toUpperCase() + name.slice(1);
function inherited(base, fields = new Map()) {
    for (const parent of schema.bases[base].extends ?? []) inherited(parent, fields);
    for (const [name, field] of Object.entries(schema.bases[base].fields ?? {})) if (!field.noGo) fields.set(name, {name, ...field});
    return fields;
}
function fieldsOf(definition) {
    const fields = new Map();
    for (const base of definition.extends ?? []) inherited(base, fields);
    return (definition.members ?? []).map(field => ({...fields.get(field.name), ...field}))
        .filter(field => field.name !== "Kind" && !field.goOnly && !field.noGo);
}
function type(field) {
    if (field.list === "raw") return field.type === "string" ? null : "SyntaxNode[]";
    if (field.list) return "NodeList?";
    if (scalar.has(field.type) || Array.isArray(field.type) && field.type.every(t => t.startsWith("SyntaxKind."))) return null;
    if (!field.type) throw Error(`Unresolved field ${JSON.stringify(field)}`);
    return names.has(field.type) ? className(field.type) + "?" : "SyntaxNode?";
}
const cases = [], methods = [];
for (const [name, definition] of Object.entries(definitions)) {
    const fields = fieldsOf(definition).filter(field => type(field));
    if (!fields.length) continue;
    const nodeType = className(name);
    cases.push(`        ${nodeType} value => VisitChildrenAsync(value),`);
    methods.push(`    private async ValueTask<SyntaxNode?> VisitChildrenAsync(${nodeType} node)`, "    {");
    for (const field of fields) {
        const property = upper(field.name), fieldType = type(field);
        const hooks = {modifiers: "VisitListAsync", parameters: "VisitParametersAsync", functionBody: "VisitFunctionBodyAsync", topLevelStatements: "VisitTopLevelStatementsAsync",
            embeddedStatement: "VisitEmbeddedStatementAsync", iterationBody: "VisitIterationBodyAsync"};
        if (field.visit && !hooks[field.visit]) throw Error(`Unknown visit hook: ${field.visit}`);
        const call = hooks[field.visit] ?? (fieldType === "NodeList?" ? "VisitListAsync" : fieldType === "SyntaxNode[]" ? "VisitArrayAsync" : "VisitAsync");
        const cast = fieldType.endsWith("Node?") && fieldType !== "SyntaxNode?" ? `(${fieldType})` : "";
        methods.push(`        var updated${property} = ${cast}await ${call}(node.${property}).ConfigureAwait(false);`);
    }
    methods.push(`        if (${fields.map(field => `ReferenceEquals(updated${upper(field.name)}, node.${upper(field.name)})`).join(" && ")})`, "            return node;", "        var result = Context.Clone(node);");
    for (const field of fields) methods.push(`        result.${upper(field.name)} = updated${upper(field.name)};`);
    methods.push("        return result;", "    }", "");
}
const rewriter = ["// <auto-generated />", "#nullable enable", `// ast.json SHA256 ${sha256(bytes)}`,
    "using TypeScript.Compiler.Ast;", "", "namespace TypeScript.Compiler.Emission;", "", "public abstract partial class SyntaxRewriter", "{",
    "    protected ValueTask<SyntaxNode?> VisitEachChildAsync(SyntaxNode node) => node switch", "    {", ...cases,
    "        _ => ValueTask.FromResult<SyntaxNode?>(node)", "    };", "", ...methods, "}", ""].join("\n");

async function save(name, text) {
    const file = path.join(root, "csharp/src/TypeScript.Compiler/Emission", name);
    if (process.argv.includes("--check")) {
        if ((await readFile(file, "utf8")).replaceAll("\r\n", "\n") !== text) throw Error(`Stale ${name}`);
    } else {
        await mkdir(path.dirname(file), {recursive: true});
        await writeFile(file, text);
    }
}
await save("SyntaxRewriter.generated.cs", rewriter);

const flagBytes = await readFile(path.join(root, "tsc/internal/printer/emitflags.go"));
const flagSource = flagBytes.toString().replaceAll("\r", "");
const flagBlock = flagSource.match(/const \(\n([\s\S]*?)\n\)/)?.[1];
if (!flagBlock) throw Error("Missing emit flags");
const flags = flagBlock.split("\n").map(line => line.replace(/\/\/.*$/, "").trim()).filter(Boolean).map((line, index) => {
    const match = line.match(/^(EF\w+)(?:\s+EmitFlags\s*=\s*1\s*<<\s*iota)?$/);
    if (!match) throw Error(`Unknown emit flag: ${line}`);
    return `    ${match[1].slice(2)} = 1 << ${index},`;
});
const aliases = [...flagSource.matchAll(/^\s*(EF\w+)\s*=\s*(EF\w+(?:\s*\|\s*EF\w+)*)\s*(?:\/\/.*)?$/gm)]
    .map(([, name, value]) => `    ${name.slice(2)} = ${value.replaceAll(/\bEF(\w+)/g, "$1").trim()},`);
await save("EmitFlags.generated.cs", ["// <auto-generated />", `// emitflags.go SHA256 ${sha256(flagBytes)}`,
    "namespace TypeScript.Compiler.Emission;", "", "[Flags]", "public enum EmitFlags : uint", "{", "    None = 0,", ...flags, ...aliases, "}", ""].join("\n"));

const helperBytes = await readFile(path.join(root, "tsc/internal/printer/helpers.go"));
const helperSource = helperBytes.toString().replaceAll("\r", "");
const starts = [...helperSource.matchAll(/^var (\w+) = &EmitHelper\{/gm)];
const helpers = new Map();
for (let i = 0; i < starts.length; i++) {
    const variable = starts[i][1], body = helperSource.slice(starts[i].index, starts[i + 1]?.index);
    const field = name => body.match(new RegExp(`\\b${name}:\\s*("(?:[^"\\\\]|\\\\.)*")`))?.[1];
    const name = field("Name"), importName = field("ImportName") ?? '""';
    const text = body.match(/\bText:\s*`([^`]*)`/)?.[1];
    const priority = body.match(/\bPriority:\s*&Priority\{(\d+)\}/)?.[1] ?? "null";
    const scoped = body.match(/\bScoped:\s*(true|false)/)?.[1];
    const dependencies = body.match(/\bDependencies:\s*\[\]\*EmitHelper\{([^}]+)\}/)?.[1].split(",").map(x => x.trim()).filter(Boolean) ?? [];
    if (!name || !scoped) throw Error(`Unknown helper: ${variable}`);
    let callback = "null";
    if (text === undefined) {
        const expression = body.match(/TextCallback:[\s\S]*?\breturn ([\s\S]*?)\n\t\},/)?.[1].replaceAll(/\s*\+\s*/g, " + ");
        if (!expression || !/^(?:"(?:[^"\\]|\\.)*"|makeUniqueName\("_superIndex"\))(?: \+ (?:"(?:[^"\\]|\\.)*"|makeUniqueName\("_superIndex"\)))*$/.test(expression))
            throw Error(`Unknown helper text factory: ${variable}`);
        callback = `static makeUniqueName => ${expression.replaceAll(/"(?:[^"\\]|\\.)*"/g, s => s + "u8")}`;
    }
    helpers.set(variable, {variable, name, importName, text, scoped, priority, dependencies, callback});
}
const ordered = [], visited = new Set(), visiting = new Set();
function visit(name) {
    if (visited.has(name)) return;
    const helper = helpers.get(name);
    if (!helper || visiting.has(name)) throw Error(`Unknown or cyclic helper dependency: ${name}`);
    visiting.add(name);
    for (const dependency of helper.dependencies) visit(dependency);
    visiting.delete(name);
    visited.add(name);
    ordered.push(helper);
}
for (const name of helpers.keys()) visit(name);
const helperName = value => upper(value.replace(/Helper$/, ""));
const helperLines = ["// <auto-generated />", "#nullable enable", `// helpers.go SHA256 ${sha256(helperBytes)}`,
    "using TypeScript.Compiler.Text;", "", "namespace TypeScript.Compiler.Emission;", "", "public static class EmitHelpers", "{"];
for (const helper of ordered) {
    helperLines.push(`    public static readonly EmitHelper ${helperName(helper.variable)} = new(${helper.name}u8, ${helper.importName}u8,`,
        `        ${JSON.stringify(helper.text ?? "")}u8, ${helper.scoped}, ${helper.priority}, [${helper.dependencies.map(helperName).join(", ")}], ${helper.callback});`, "");
}
helperLines.push(`    public static IReadOnlyList<EmitHelper> All { get; } = Array.AsReadOnly<EmitHelper>([${[...helpers.keys()].map(helperName).join(", ")}]);`, "}", "");
await save("EmitHelpers.generated.cs", helperLines.join("\n"));

const jsxBytes = await readFile(path.join(root, "tsc/internal/transformers/jsxtransforms/jsx.go"));
const entityBlock = jsxBytes.toString().match(/var entities = map\[string\]rune\{([\s\S]*?)\n\}/)?.[1];
if (!entityBlock) throw Error("Missing JSX entity table");
const entities = [...entityBlock.matchAll(/"(\w+)":\s*(0x[0-9A-Fa-f]+),/g)];
if (entities.length < 250) throw Error("Incomplete JSX entity table");
await save("JsxTransformer.Entities.generated.cs", ["// <auto-generated />", `// jsx.go SHA256 ${sha256(jsxBytes)}`,
    "using TypeScript.Compiler.Text;", "", "namespace TypeScript.Compiler.Emission;", "", "internal sealed partial class JsxTransformer", "{",
    "    private static readonly Dictionary<Utf8String, int> Entities = new()", "    {",
    ...entities.map(([, name, value]) => `        [\"${name}\"u8] = ${value},`), "    };", "}", ""].join("\n"));
console.log(`Generated child rewriting for ${cases.length} AST shapes, ${flags.length} emit flags and ${helpers.size} runtime helpers`);
