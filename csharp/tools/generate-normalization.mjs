import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { output, root, run, sha256 } from "./common.mjs";

const option = (key, fallback) => process.argv.includes(key) ? process.argv[process.argv.indexOf(key) + 1] : fallback;
const go = option("--go", "D:/go1.27.1-20260904.9.windows-amd64/go/bin/go.exe");
const directory = path.join(output, "normalization-generator");
await mkdir(directory, { recursive: true });
const program = `package main
import("encoding/json";"os";"unicode";"reflect";"golang.org/x/text/unicode/norm")
func main(){
 decomposition:=[][2]any{}; classes,upper,streamSafe:=[][2]int{},[][2]int{},[][2]int{}; marks,upperCase,lowerCase:=[]int{},[]int{},[]int{}
 for r:=rune(0);r<=unicode.MaxRune;r++ {
  if r>=0xD800&&r<=0xDFFF {continue}
  s:=string(r)
  if d:=norm.NFD.String(s);d!=s && !(r>=0xAC00&&r<=0xD7A3) {rr:=[]int{};for _,v:=range d {rr=append(rr,int(v))};decomposition=append(decomposition,[2]any{int(r),rr})}
  p:=norm.NFD.PropertiesString(s)
  if c:=p.CCC();c!=0 {classes=append(classes,[2]int{int(r),int(c)})}
  v:=reflect.ValueOf(p); nLead,nTrail:=v.FieldByName("nLead").Uint(),v.FieldByName("flags").Uint()&3
  if n:=int(nLead|nTrail<<2);n!=0 {streamSafe=append(streamSafe,[2]int{int(r),n})}
  if unicode.Is(unicode.Mn,r) {marks=append(marks,int(r))}
  if unicode.IsUpper(r) {upperCase=append(upperCase,int(r))}
  if unicode.IsLower(r) {lowerCase=append(lowerCase,int(r))}
  if v:=unicode.ToUpper(r);v!=r {upper=append(upper,[2]int{int(r),int(v)})}
 }
 if err:=json.NewEncoder(os.Stdout).Encode(map[string]any{"version":unicode.Version,"normalizationVersion":norm.Version,"decomposition":decomposition,"classes":classes,"marks":marks,"upperCase":upperCase,"lowerCase":lowerCase,"upper":upper,"streamSafe":streamSafe});err!=nil {panic(err)}
}
`;
const source = path.join(directory, "main.go");
await writeFile(source, program);
const data = JSON.parse(await run(go, ["run", source], { cwd: path.join(root, "tsc"), env: { ...process.env, GOWORK: "off", GOTOOLCHAIN: "local" } }));
const lines = ["// <auto-generated />", `// Go Unicode ${data.version}, NFD ${data.normalizationVersion}; table SHA256 ${sha256(JSON.stringify(data))}`,
    "namespace TypeScript.Compiler.Semantics;", "internal static partial class GoUnicode", "{"];
function array(name, values) {
    lines.push(`    private static ReadOnlySpan<int> ${name} =>`, "    [");
    for (let i = 0; i < values.length; i += 12) lines.push("        " + values.slice(i, i + 12).map(value => `0x${value.toString(16)}`).join(", ") + ",");
    lines.push("    ];");
}
function ranges(values) {
    const result = [];
    for (const value of values) {
        if (result.length && result.at(-1) === value - 1) result[result.length - 1] = value;
        else result.push(value, value);
    }
    return result;
}
const index = [], expanded = [];
for (const [point, sequence] of data.decomposition) {
    index.push(point, expanded.length);
    expanded.push(sequence.length, ...sequence);
}
array("DecompositionIndex", index);
array("Decompositions", expanded);
array("CombiningClasses", data.classes.flat());
array("StreamSafeCounts", data.streamSafe.flat());
array("NonspacingMarkRanges", ranges(data.marks));
array("UpperCaseRanges", ranges(data.upperCase));
array("LowerCaseRanges", ranges(data.lowerCase));
array("UpperMap", data.upper.flat());
lines.push("}", "");
const target = path.join(root, "csharp/src/TypeScript.Compiler/Semantics/GoUnicode.Normalization.generated.cs"), text = lines.join("\n");
if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")).replaceAll("\r\n", "\n") !== text) throw Error(`Stale ${target}`);
}
else await writeFile(target, text);
console.log(JSON.stringify({ version: data.version, normalizationVersion: data.normalizationVersion, decompositionMappings: data.decomposition.length,
    combiningClasses: data.classes.length, nonspacingMarks: data.marks.length, tableSha256: sha256(JSON.stringify(data)) }));
